#!/usr/bin/env bash
# Regenerates the ER AAC LC (object type 17) and ER AAC LTP (object type 19) fixtures from the repository's own stream generator (tools/sauti_aac_gen.c --er [--ltp]) and the muxers
# tools/mux_raw_aus_mp4.py / mux_raw_aus_loas.py.  Error-resilient syntax WITHOUT resilience tools (epConfig 0): no element ids, no ID_END, an instance tag per element, tns_data after the
# gain-control flag.  NOT from an encoder and NOT from user material; the repository carries the OUTPUT.
#   erlc_*      ER AAC LC: FFmpeg and FAAD2 decode it (mono / stereo / 960 lines / 3.0 / 5.1)
#   erltp_*     ER AAC LTP: FFmpeg cannot (its ASC parser refuses object type 19), FAAD2 decodes mono (coarse long-term buffer, ~67 dB) and fails on stereo; the stereo / 5.1 files are checked by the
#               EQUIVALENCE test: the same random content (same seed) written in the plain syntax (erplain_*: AAC-LC / AAC LTP, which FFmpeg decodes) must decode to the identical PCM
#   erplain_*   the same seeds in the plain syntax: AAC-LC (erplain_lc_*) and AAC LTP (erplain_ltp_*)
# usage: tests/data/make_er_fixtures.sh   (needs python3 and a built build/sauti_aac_gen: make build/sauti_aac_gen)
set -euo pipefail
cd "$(dirname "$0")"
GEN=../../build/sauti_aac_gen; MUX=../../tools/mux_raw_aus_mp4.py; LOAS=../../tools/mux_raw_aus_loas.py
[ -x "$GEN" ] || { echo "build the generator first: make build/sauti_aac_gen"; exit 1; }
W="$(mktemp -d "${TMPDIR:-/tmp}/sauti-er.XXXXXX")"; trap 'rm -rf -- "${W:?}"' EXIT
g() { n="$1"; fl="$2"; shift 2; "$GEN" "$W/$n" --level 130 --amp 3 "$@" >/dev/null; python3 -I "$MUX" "$W/$n" "$n.m4a" "$fl"; }
C="--ms --tns --short --kbd"
g erlc_st        1024 --er --channels 2 --frames 40 $C --seed 101
g erlc_mono      1024 --er --channels 1 --frames 40 $C --seed 102
g erlc960_st     960  --er --frame 960 --channels 2 --frames 40 $C --seed 103
g erlc_c3        1024 --er --config 3 --frames 12 $C --seed 104
g erlc_c6        1024 --er --config 6 --frames 12 $C --seed 105
g erlc_c7        1024 --er --config 7 --frames 12 $C --seed 106
g erltp_st       1024 --er --ltp --channels 2 --frames 40 $C --seed 111
g erltp_mono     1024 --er --ltp --channels 1 --frames 40 $C --seed 112
g erltp_c6       1024 --er --ltp --config 6 --frames 12 $C --seed 113
g erltp_c7       1024 --er --ltp --config 7 --frames 12 $C --seed 114
g erplain_lc_st  1024 --channels 2 --frames 40 $C --seed 101
g erplain_lc_c6  1024 --config 6 --frames 12 $C --seed 105
g erplain_lc_c7  1024 --config 7 --frames 12 $C --seed 106
g erplain_ltp_st 1024 --ltp --channels 2 --frames 40 $C --seed 111
g erplain_ltp_c6 1024 --ltp --config 6 --frames 12 $C --seed 113
g erplain_ltp_c7 1024 --ltp --config 7 --frames 12 $C --seed 114
python3 -I "$LOAS" "$W/erlc_st" erlc_st.loas
python3 -I "$LOAS" "$W/erltp_st" erltp_st.loas
python3 -I - "$W" ../test_aac_er_syntax_vectors.h <<'PY'
import struct, sys
d, out = sys.argv[1], sys.argv[2]
text = ["/* Generated by tests/data/make_er_fixtures.sh: the first access units of erlc_st.m4a (ER AAC LC stereo), erltp_st.m4a (ER AAC LTP stereo) and erlc_c6.m4a (ER AAC LC 5.1). */\n"]
for name, n_au in (("erlc_st", 6), ("erltp_st", 6), ("erlc_c6", 3)):
    raw = open("%s/%s.aus" % (d, name), "rb").read(); aus = []; p = 0
    while p + 4 <= len(raw):
        n = struct.unpack('>I', raw[p:p+4])[0]; aus.append(raw[p+4:p+4+n]); p += 4 + n
    for i in range(n_au): text.append("static const uint8_t %s_au%d[] = {%s};\n" % (name, i, ",".join("0x%02x" % b for b in aus[i])))
open(out, "w").write("".join(text))
PY
