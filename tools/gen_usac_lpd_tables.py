    ('ixheaacd_avq_rom.c', 'ixheaacd_signed_leader_is', 'sauti_usac_lpd_signed_leader_is', (226,), 'cardinality offsets of the signed leaders'),
    ('ixheaacd_avq_rom.c', 'ixheaacd_pos_abs_leaders_a3', 'sauti_usac_lpd_pos_abs_leaders_a3', (9,), 'absolute leader of every cardinality interval, codebooks Q2 and Q3'),
    ('ixheaacd_avq_rom.c', 'ixheaacd_pos_abs_leaders_a4', 'sauti_usac_lpd_pos_abs_leaders_a4', (28,), 'the same for Q4'),
    ('ixheaacd_avq_rom.c', 'ixheaacd_cardinality_offset_table_i3', 'sauti_usac_lpd_card_offset_i3', (9,), 'cardinality offsets, Q2 / Q3'),
    ('ixheaacd_avq_rom.c', 'ixheaacd_cardinality_offset_tab_i4', 'sauti_usac_lpd_card_offset_i4', (28,), 'cardinality offsets, Q4'),
    ('ixheaacd_avq_rom.c', 'ixheaacd_weight_table_avq', 'sauti_usac_lpd_lsf_weight', (256, 16), 'per first-stage vector weights of the AVQ residual of an absolutely coded LSF set'),
    ('ixheaacd_rom.c', 'ixheaacd_dico_lsf_abs_8b_flt', 'sauti_usac_lpd_lsf_codebook', (256, 16), 'first stage LSF codebook (8 bits, 16 line spectral frequencies, Hz)'),
    ('ixheaacd_rom.c', 'ixheaacd_int_leave_gain_table', 'sauti_usac_lpd_gain_table', (128, 2), 'ACELP gain quantiser: pitch gain and normalised codebook gain per 7-bit index'),
    ('ixheaacd_avq_rom.c', 'ixheaacd_fir_lp_filt', 'sauti_usac_lpd_bpf_fir', (13,), 'low-pass FIR of the long-term (bass) post-filter, taps 0..12 (symmetric)'),
    ('ixheaacd_avq_rom.c', 'ixheaacd_interpol_filt', 'sauti_usac_lpd_interpol_filt', (65,), 'ACELP adaptive codebook interpolation filter (1/4 sample resolution, 16 taps per side)'),
