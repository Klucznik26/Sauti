#!/usr/bin/env python3
"""Generates src/decoders/modern/aac/sauti_aac_eld_sac_tables.c and include/sauti_aac_eld_sac_tables.h: the DATA of the low delay MPEG Surround (ELD v2): the maps from the 64 QMF bands to the 4 .. 23 parameter bands
(ISO/IEC 23003-1 mapping of the low delay profile), read from sac_rom.cpp of the FDK AAC codec (libSACdec, "kernels_N_to_64"; Fraunhofer FDK AAC Codec Library licence, data only, no code is taken; the owner of
Sauti allowed this on 2026-11-24, register entry in docs/BIBLIOTEKA_PLAN.md).  The decoder logic is written for Sauti.
usage: tools/gen_eld_sac_tables.py [SAC_ROM_CPP]   (default ~/tmp_ayo/fdkdbg/src/libSACdec/src/sac_rom.cpp; read-only, outside the repository)"""
import os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else '~/tmp_ayo/fdkdbg/src/libSACdec/src/sac_rom.cpp')
text = open(SRC, encoding='utf-8', errors='replace').read()
def vals(name):
    m = re.search(r'\b' + name + r'\s*\[[^\]]*\]\s*=\s*\{(.*?)\};', text, re.S)
    if not m: raise SystemExit('table %s not found' % name)
    return [int(x) for x in re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S).replace('\n', ' ').split(',') if x.strip()]
bands = [4, 5, 7, 9, 12, 15, 23]
tabs = {n: vals('kernels_%d_to_64' % n)[:64] for n in bands}
for n, v in tabs.items():
    assert len(v) == 64 and v[0] == 0 and v[-1] == n - 1 and all(0 <= b - a <= 1 for a, b in zip(v, v[1:])), n
# the all-pass numerators of the low delay decorrelator (reverb bands 1..3), seed 2: the seed the 2-1-2 tree uses (FDK_decorrelate.cpp, DecorrNumeratorReal{1,2,3}_LD[2]); value = fixed point / 2^30, the last
# numerator coefficient is 1.0 (0x40000000)
DEC = os.path.expanduser(os.path.join(os.path.dirname(SRC), '..', '..', 'libFDK', 'src', 'FDK_decorrelate.cpp'))
dtext = open(DEC, encoding='utf-8', errors='replace').read()
def decor(rb, order):
    m = re.search(r'DecorrNumeratorReal%d_LD\[[^=]*=\s*\{(.*?)\n\};' % rb, dtext, re.S)
    if not m: raise SystemExit('numerator %d not found' % rb)
    seeds = re.findall(r'\{([^{}]*)\}', m.group(1))
    v = [int(x, 16) for x in re.findall(r'DECORR\((0x[0-9a-fA-F]+)\)', seeds[2])]
    v = [x - (1 << 32) if x >= (1 << 31) else x for x in v][:order + 1]
    assert len(v) == order + 1 and v[order] == 0x40000000, (rb, len(v), v[-1:])
    return v
orders = {1: 15, 2: 6, 3: 3}
nums = {rb: decor(rb, o) for rb, o in orders.items()}
hdr = '''#ifndef SAUTI_AAC_ELD_SAC_TABLES_H
#define SAUTI_AAC_ELD_SAC_TABLES_H
/* GENERATED by tools/gen_eld_sac_tables.py - do not edit.  Source: kernels_N_to_64 of libSACdec/src/sac_rom.cpp of the FDK AAC codec (data only; see the script and docs/BIBLIOTEKA_PLAN.md). */
#include <stdint.h>
/* parameter band of every one of the 64 QMF bands, for 4, 5, 7, 9, 12, 15 and 23 parameter bands (index by sauti_aac_eld_sac_kernel(freq_res)) */
const uint8_t *sauti_aac_eld_sac_kernel(unsigned parameter_bands);
/* all-pass numerator of the decorrelator in reverb band 1, 2, 3 (orders 15, 6, 3; order + 1 coefficients, the last is 1.0); the denominator is the numerator reversed */
extern const float sauti_aac_eld_sac_decor_num1[16], sauti_aac_eld_sac_decor_num2[7], sauti_aac_eld_sac_decor_num3[4];
#endif
'''
c = '/* GENERATED by tools/gen_eld_sac_tables.py - do not edit.  Data of kernels_N_to_64 (libSACdec/src/sac_rom.cpp, FDK AAC codec; provenance in the generator and docs/BIBLIOTEKA_PLAN.md). */\n#include "sauti_aac_eld_sac_tables.h"\n'
for n in bands:
    c += 'static const uint8_t kernel_%d[64] = {\n' % n
    for i in range(0, 64, 16): c += '    ' + ', '.join(str(x) for x in tabs[n][i:i + 16]) + ',\n'
    c += '};\n'
c += 'const uint8_t *sauti_aac_eld_sac_kernel(unsigned n) {\n    switch (n) {\n'
for n in bands: c += '    case %du: return kernel_%d;\n' % (n, n)
c += '    default: return 0;\n    }\n}\n'
for rb, o in orders.items():
    c += 'const float sauti_aac_eld_sac_decor_num%d[%d] = { %s };\n' % (rb, o + 1, ', '.join(repr(x / float(1 << 30)) + 'f' for x in nums[rb]))
open(os.path.join(ROOT, 'include/sauti_aac_eld_sac_tables.h'), 'w').write(hdr)
open(os.path.join(ROOT, 'src/decoders/modern/aac/sauti_aac_eld_sac_tables.c'), 'w').write(c)
print('ok')
