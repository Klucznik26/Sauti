import os, re, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
XAAC = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else '~/Sauti-tools/libxaac')
SRC = 'ixheaacd_pvc_rom.c'
# (name in libxaac, new name, C type, dimensions, one-line meaning)
TABLES = [
    ('ixheaacd_pvc_smoothing_wind_tab_ns4', 'sauti_usac_pvc_smooth_ns4', 'float', (4,), 'time smoothing window of the low band energies, mode 1, ns_mode 1'),
    ('ixheaacd_pvc_smoothing_wind_tab_ns16', 'sauti_usac_pvc_smooth_ns16', 'float', (16,), 'the same, mode 1, ns_mode 0'),
    ('ixheaacd_pvc_smoothing_wind_tab_ns3', 'sauti_usac_pvc_smooth_ns3', 'float', (3,), 'the same, mode 2, ns_mode 1'),
    ('ixheaacd_pvc_smoothing_wind_tab_ns12', 'sauti_usac_pvc_smooth_ns12', 'float', (12,), 'the same, mode 2, ns_mode 0'),
    ('ixheaacd_pred_coeff_pvc_id_boundaries_1', 'sauti_usac_pvc_id_boundary_m1', 'uint8_t', (2,), 'pvc_id boundaries of the three coefficient groups, mode 1'),
    ('ixheaacd_q_factor_table_mode_1', 'sauti_usac_pvc_qfac_m1', 'float', (4,), 'quantiser step of the prediction coefficients (three low band groups and the offset), mode 1'),
    ('ixheaacd_pred_coeff_table_1_mode_1', 'sauti_usac_pvc_coef1_m1', 'int8_t', (3, 3, 8), 'prediction coefficients per id group, low band group and high band group, mode 1'),
    ('ixheaacd_pred_coeff_table_2_mode_1', 'sauti_usac_pvc_coef2_m1', 'int8_t', (128, 8), 'offsets per pvc_id and high band group, mode 1'),
    ('ixheaacd_pred_coeff_pvc_id_boundaries_2', 'sauti_usac_pvc_id_boundary_m2', 'uint8_t', (2,), 'pvc_id boundaries of the three coefficient groups, mode 2'),
    ('ixheaacd_q_factor_table_mode_2', 'sauti_usac_pvc_qfac_m2', 'float', (4,), 'quantiser step of the prediction coefficients, mode 2'),
    ('ixheaacd_pred_coeff_table_1_mode_2', 'sauti_usac_pvc_coef1_m2', 'int8_t', (3, 3, 6), 'prediction coefficients per id group, low band group and high band group, mode 2'),
    ('ixheaacd_pred_coeff_table_2_mode_2', 'sauti_usac_pvc_coef2_m2', 'int8_t', (128, 6), 'offsets per pvc_id and high band group, mode 2'),
]

def read_values(path, name):
    src = open(path, encoding='utf-8', errors='replace').read()
    m = re.search(r'\b' + re.escape(name) + r'\s*(\[[^=;]*\])+\s*=\s*\{', src)
    if not m: raise SystemExit('table %s not found in %s' % (name, path))
    i = m.end(); depth = 1; j = i
    while depth:
        c = src[j]; depth += (c == '{') - (c == '}'); j += 1
    body = re.sub(r'//[^\n]*|/\*.*?\*/', '', src[i:j - 1], flags=re.S)
    body = re.sub(r'\(\s*(?:WORD8|UWORD8)\s*\)', '', body).replace('{', ' ').replace('}', ' ')
    vals = []
    for item in body.split(','):
        item = item.strip()
        if not item: continue
        if not item.lower().startswith('0x'): item = re.sub(r'(?<=[0-9.])[fF]\b', '', item)          # 1.5f -> 1.5
        if re.fullmatch(r'0[xX][0-9a-fA-F]+', item): vals.append(int(item, 16))
        elif re.fullmatch(r'[-+0-9.eE/ ]+', item): vals.append(eval(item))      # plain numbers and the quotients of the quantiser steps
        else: raise SystemExit('%s: cannot read %r' % (name, item))
    return vals

def main():
    rev = subprocess.run(['git', '-C', XAAC, 'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip()
    hdr = ['#ifndef SAUTI_USAC_PVC_TABLES_H', '#define SAUTI_USAC_PVC_TABLES_H', '#include <stdint.h>',
           '/* Normative data tables of predictive vector coding (PVC) of eSBR (ISO/IEC 23003-3).  GENERATED by tools/gen_usac_pvc_tables.py - do not edit.', ' * Source of the data: libxaac (ittiam-systems/libxaac, commit %s), Apache License 2.0, Copyright (C) 2018 The Android Open Source Project,' % rev,
           ' * originally developed and contributed by Ittiam Systems Pvt. Ltd; licence text and NOTICE in third_party/libxaac/.  Only the numbers are taken from there; the decoder logic is written for Sauti.', ' * Provenance register: docs/BIBLIOTEKA_PLAN.md ("Rejestr tablic LPD z libxaac"). */']
    src = ['/* GENERATED by tools/gen_usac_pvc_tables.py from libxaac (commit %s, Apache License 2.0, third_party/libxaac/LICENSE) - do not edit.  See include/sauti_usac_pvc_tables.h. */' % rev, '#include "sauti_usac_pvc_tables.h"', '']
    for old, new, c, dims, doc in TABLES:
        vals = read_values(os.path.join(XAAC, 'decoder', SRC), old)
        n = 1
        for d in dims: n *= d
        if len(vals) != n: raise SystemExit('%s: %d values, expected %d' % (old, len(vals), n))
        if c == 'int8_t': vals = [v - 256 if v > 127 else v for v in vals]
        toks = [('%.9gf' % v) if c == 'float' else str(v) for v in vals]
        toks = [t if ('.' in t or 'e' in t or c != 'float') else t.replace('f', '.0f') for t in toks]
        dd = ''.join('[%d]' % d for d in dims)
        hdr.append('extern const %s %s%s;   /* %s (libxaac: %s, %s) */' % (c, new, dd, doc, old, SRC))
        src.append('const %s %s%s = {' % (c, new, dd))
        if len(dims) == 3:
            for a in range(dims[0]):
                src.append('    {')
                for r in range(dims[1]):
                    o = (a * dims[1] + r) * dims[2]
                    src.append('        { ' + ', '.join(toks[o:o + dims[2]]) + ' },')
                src.append('    },')
        else:
            per = dims[-1] if len(dims) > 1 else 8
            multi = len(dims) > 1
            for k in range(0, n, per): src.append('    ' + ('{ ' if multi else '') + ', '.join(toks[k:k + per]) + (' },' if multi else ','))
        src.append('};')
    hdr.append('#endif')
    open(os.path.join(ROOT, 'include/sauti_usac_pvc_tables.h'), 'w').write('\n'.join(hdr) + '\n')
    open(os.path.join(ROOT, 'src/decoders/modern/aac/sauti_usac_pvc_tables.c'), 'w').write('\n'.join(src) + '\n')
    print('%d tables, libxaac %s' % (len(TABLES), rev))
main()
