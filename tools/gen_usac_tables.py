#!/usr/bin/env python3
"""Regenerates src/decoders/modern/aac/sauti_usac_tables.c from the USAC tables of an FFmpeg source tree (libavcodec/aactab.c, LGPL-2.1-or-later; see the licensing note
in the generated file and docs/BIBLIOTEKA_PLAN.md).  The numbers are the normative tables of ISO/IEC 23003-3; they are copied, not derived.
usage: gen_usac_tables.py PATH/TO/libavcodec/aactab.c > src/decoders/modern/aac/sauti_usac_tables.c"""
import re, sys
t = open(sys.argv[1]).read()
def body(name, open_pat=None):
    i = t.index(name); j = t.index('{', i); depth = 0; k = j
    while True:
        if t[k] == '{': depth += 1
        elif t[k] == '}':
            depth -= 1
            if depth == 0: break
        k += 1
    return t[j+1:k]
def nums(s): return [x for x in re.findall(r'[-+]?(?:0[xX][0-9a-fA-F]+|\d+\.\d*(?:[eE][-+]?\d+)?|\d+)', re.sub(r'/\*.*?\*/', '', s))]
def arr(ctype, cname, name, count, per_line, vals=None):
    v = vals if vals is not None else nums(body(name))
    assert len(v) == count, (name, len(v), count)
    out = ["const %s %s[%d] = {" % (ctype, cname, count)]
    for i in range(0, count, per_line): out.append("    " + ", ".join(v[i:i+per_line]) + ",")
    out.append("};"); return "\n".join(out)
o = []
o.append("""/* USAC (ISO/IEC 23003-3) constant tables: arithmetic coder (context hash, cumulative frequencies), 768-line band layouts, TNS / noise filling parameters, complex-prediction MDST filters.
 * LICENSING: GENERATED by tools/gen_usac_tables.py from FFmpeg libavcodec/aactab.c (Copyright (c) 2024 Lynne and others, LGPL-2.1-or-later).  The numbers are normative tables of the standard;
 * this file is part of the replaceable table module listed in docs/BIBLIOTEKA_PLAN.md and must be shipped under the LGPL with its source. */
#include "sauti_usac_tables.h"
""")
# 2-D tables
msb = nums(body("ff_aac_ac_msb_cdfs[64][17]")); assert len(msb) == 64*17
o.append("const uint16_t sauti_usac_ac_msb_cdf[64][17] = {")
for r in range(64): o.append("    {" + ", ".join(msb[r*17:(r+1)*17]) + "},")
o.append("};")
lsb = nums(body("ff_aac_ac_lsb_cdfs[3][4]")); assert len(lsb) == 12
o.append("const uint16_t sauti_usac_ac_lsb_cdf[3][4] = {")
for r in range(3): o.append("    {" + ", ".join(lsb[r*4:(r+1)*4]) + "},")
o.append("};")
o.append(arr("uint8_t", "sauti_usac_ac_lookup", "ff_aac_ac_lookup_m[742]", 742, 16))
o.append(arr("uint32_t", "sauti_usac_ac_hash", "ff_aac_ac_hash_m[742]", 742, 8))
# band layouts: named arrays swb_offset_768_* / swb_offset_96_*; #define aliases are resolved
def named(prefix):
    d = {}
    for m in re.finditer(r'static const uint16_t (swb_offset_%s_\d+)\[\]\s*=\s*\{(.*?)\};' % prefix, t, re.S): d[m.group(1)] = nums(m.group(2))
    for m in re.finditer(r'#define (swb_offset_%s_\d+) (swb_offset_%s_\d+)' % (prefix, prefix), t): d[m.group(1)] = d[m.group(2)]
    return d
def table_of(listname, d):
    names = re.findall(r'swb_offset_\w+', body(listname + "[]"))
    return [d[n] for n in names]
for prefix, listname, cname in (("768", "ff_swb_offset_768", "sauti_usac_swb768"), ("96", "ff_swb_offset_96", "sauti_usac_swb96")):
    tabs = table_of(listname, named(prefix)); assert len(tabs) == 13
    for i, v in enumerate(tabs): o.append("static const uint16_t %s_%d[%d] = { %s };" % (cname, i, len(v), ", ".join(v)))
    o.append("const uint16_t *const %s[13] = { %s };" % (cname, ", ".join("%s_%d" % (cname, i) for i in range(13))))
def small(ctype, cname, name, n):
    v = nums(body(name)); assert len(v) == n, (name, len(v)); return "const %s %s[%d] = { %s };" % (ctype, cname, n, ", ".join(v))
o.append(small("uint8_t", "sauti_usac_num_swb768", "ff_aac_num_swb_768[]", 13))
o.append(small("uint8_t", "sauti_usac_num_swb96", "ff_aac_num_swb_96[]", 13))
o.append(small("uint8_t", "sauti_usac_tns_max_bands_1024", "ff_tns_max_bands_usac_1024[]", 13))
o.append(small("uint8_t", "sauti_usac_tns_max_bands_128", "ff_tns_max_bands_usac_128[]", 13))
o.append(small("uint8_t", "sauti_usac_noise_fill_start[4]".split('[')[0], "ff_usac_noise_fill_start_offset[2][2]", 4))
o.append(small("int", "sauti_usac_samplerate", "ff_aac_usac_samplerate[32]", 32))
f = nums(body("ff_aac_usac_mdst_filt_cur[4 /* Window */][4 /* Shape */][7]")); assert len(f) == 112
o.append("const float sauti_usac_mdst_filt_cur[4][4][7] = {")
for w in range(4):
    o.append("    {")
    for s in range(4): o.append("        { " + ", ".join(x + "f" for x in f[(w*4+s)*7:(w*4+s+1)*7]) + " },")
    o.append("    },")
o.append("};")
print("\n".join(o))
