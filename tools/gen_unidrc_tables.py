#!/usr/bin/env python3
"""Generates src/decoders/modern/aac/sauti_unidrc_tables.c and include/sauti_unidrc_tables.h: the DATA tables of the MPEG-D DRC (uniDRC, ISO/IEC 23003-4) bitstream decoder: the delta gain code tables of the gain
coding profiles 0 / 1 (25 entries) and 2 (49 entries) and the slope code table (15 entries), read from decoder/drc_src/impd_drc_rom.c of libxaac (Apache License 2.0, Copyright (C) 2018 The Android Open Source
Project, originally developed and contributed by Ittiam Systems Pvt. Ltd; third_party/libxaac/NOTICE) - data only, the decoder logic is written for Sauti (register: docs/BIBLIOTEKA_PLAN.md).
usage: tools/gen_unidrc_tables.py [LIBXAAC_DIR]   (default ~/Sauti-tools/libxaac; read-only)"""
import os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
XAAC = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else '~/Sauti-tools/libxaac')
t = open(os.path.join(XAAC, 'decoder', 'drc_src', 'impd_drc_rom.c'), encoding='utf-8', errors='replace').read()
def table(name):
    m = re.search(name + r'\s*\[[^\]]*\]\s*=\s*\{(.*?)\n?\};', t, re.S)
    if not m: raise SystemExit('table %s not found' % name)
    return [tuple(float(x) if '.' in x else int(x, 0) for x in re.sub(r'(\.\d+)f\b', r'\1', row).split(',') if x.strip()) for row in re.findall(r'\{([^{}]*)\}', m.group(1))]
g01, g2, slope = table('ia_drc_gain_tbls_prof_0_1'), table('ia_drc_gain_tbls_prof_2'), table('slope_code_tbl_entries_by_size')
assert len(g01) == 25 and len(g2) == 49 and len(slope) == 15 and all(len(r) == 3 for r in g01 + g2) and all(len(r) == 4 for r in slope)
for tb in (g01, g2):                                                                    # a prefix code: no code is a prefix of another
    codes = [format(c, '0%db' % s) for s, c, _ in tb]
    assert not any(a != b and b.startswith(a) for a in codes for b in codes), 'not prefix free'
sl = sorted(slope, key=lambda r: r[3])                                                    # by the last column (the index the table lists them by in the standard): kept in the source order, the decoder searches
h = '''#ifndef SAUTI_UNIDRC_TABLES_H
#define SAUTI_UNIDRC_TABLES_H
/* GENERATED by tools/gen_unidrc_tables.py from libxaac (Apache 2.0): code tables of the uniDRC gain syntax (size in bits, code, value). */
#include <stdint.h>
typedef struct { uint8_t size; uint16_t code; float value; } SautiUniDrcGainCode;
typedef struct { uint8_t size; uint16_t code; float value; } SautiUniDrcSlopeCode;
#define SAUTI_UNIDRC_GAIN01_ENTRIES 25
#define SAUTI_UNIDRC_GAIN2_ENTRIES 49
#define SAUTI_UNIDRC_SLOPE_ENTRIES 15
extern const SautiUniDrcGainCode sauti_unidrc_gain01[SAUTI_UNIDRC_GAIN01_ENTRIES], sauti_unidrc_gain2[SAUTI_UNIDRC_GAIN2_ENTRIES];
extern const SautiUniDrcSlopeCode sauti_unidrc_slope[SAUTI_UNIDRC_SLOPE_ENTRIES];
#endif
'''
c = '/* GENERATED by tools/gen_unidrc_tables.py from libxaac (Apache 2.0) - do not edit. */\n#include "sauti_unidrc_tables.h"\n'
def emit(name, typ, rows):
    s = 'const %s %s[%d] = {\n' % (typ, name, len(rows))
    for r in rows: s += '    { %d, 0x%03X, %rf },\n' % (r[0], r[1], r[2])
    return s + '};\n'
c += emit('sauti_unidrc_gain01', 'SautiUniDrcGainCode', g01) + emit('sauti_unidrc_gain2', 'SautiUniDrcGainCode', g2) + emit('sauti_unidrc_slope', 'SautiUniDrcSlopeCode', slope)
open(os.path.join(ROOT, 'include/sauti_unidrc_tables.h'), 'w').write(h)
open(os.path.join(ROOT, 'src/decoders/modern/aac/sauti_unidrc_tables.c'), 'w').write(c)
print('ok')
