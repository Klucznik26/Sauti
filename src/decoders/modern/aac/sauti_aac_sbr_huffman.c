int sauti_aac_sbr_huffman_decode(const uint8_t *bytes, size_t size,
                                  size_t *bit_offset,
                                  SautiAacSbrHuffmanBook book,
                                  int32_t *out_delta) {
    if (!bytes || !bit_offset || !out_delta ||
        (unsigned)book >= SAUTI_SBR_HUFF_TABLE_COUNT ||
        size > SIZE_MAX / 8u || *bit_offset > size * 8u)
        return 0;

    const SautiSbrHuffTrie *trie = &sbr_trees[(unsigned)book];
    size_t pos = *bit_offset;
    unsigned index = 0;

    /* Longest SBR code is 20 bits. An incomplete codeword leaves
     * the original cursor and output untouched. */
    for (unsigned depth = 0; depth < 20u; ++depth) {
        uint32_t bit = 0;
        if (!sauti_aac_bits_read_asm(bytes, size, &pos, 1u, &bit))
            return 0;
        int branch = trie->node[index][bit];
        if (branch < 0) {
            *out_delta = -branch - 64;
            *bit_offset = pos;
            return 1;
        }
        if ((unsigned)branch >= trie->count) return 0;
        index = (unsigned)branch;
    }
    return 0;
}
