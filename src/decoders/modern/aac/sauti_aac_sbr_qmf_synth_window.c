static int valid_state(const SautiAacSbrQmfSynthWindowState *s){
    if(!s || s->ready>1u || s->head>=10u ||
       (!s->ready && s->head!=0u))return 0;
    for(unsigned j=0;j<10u;j++)
        for(unsigned n=0;n<128u;n++){
            const float x=s->history[j][n];
            if(!isfinite(x) || (!s->ready && x!=0.0f))
                return 0;
        }
    return 1;
}

int sauti_aac_sbr_qmf_synth_window_coefficient(unsigned ix,float *out){
    if(!out || ix>=640u)return 0;
    *out=qmf_coeff[ix];
    return 1;
}

int sauti_aac_sbr_qmf_synth_window_64(
    const float *modulation,size_t input_count,
    unsigned slots,float *output,size_t output_count,
    SautiAacSbrQmfSynthWindowState *state){
    if(!modulation || !output || !valid_state(state) ||
       slots<1u || slots>SAUTI_AAC_SBR_QMF_SYNTH_WINDOW_SLOTS ||
       input_count<(size_t)slots*128u ||
       output_count<(size_t)slots*64u)return 0;
    /* An overlapping source/destination is explicitly unsupported:
     * the function's contract requires separate arrays. */
    if((uintptr_t)modulation <= UINTPTR_MAX -
                           (size_t)slots*128u*sizeof(*modulation) &&
       (uintptr_t)output <= UINTPTR_MAX -
                       (size_t)slots*64u*sizeof(*output)){
        const uintptr_t a=(uintptr_t)modulation;
        const uintptr_t b=(uintptr_t)output;
        const uintptr_t ae=a+(size_t)slots*128u*sizeof(*modulation);
        const uintptr_t be=b+(size_t)slots*64u*sizeof(*output);
        if(a<be && b<ae)return 0;
    }else return 0;

    /* All calculations are staged, so input/state/output stay intact
     * even when an invalid sample arrives in a late slot. */
    SautiAacSbrQmfSynthWindowState next=*state;
    float stage[SAUTI_AAC_SBR_QMF_SYNTH_WINDOW_SLOTS*64u];
    for(unsigned t=0;t<slots;t++){
        const float *block=modulation+(size_t)t*128u;
        for(unsigned n=0;n<128u;n++)
            if(!isfinite(block[n]))return 0;
        if(next.ready)
            next.head=(next.head+9u)%10u;
        else {
            next.ready=1u;next.head=0u;
        }
        memcpy(next.history[next.head],block,128u*sizeof(float));
        for(unsigned n=0;n<64u;n++){
            double sum=0.0;
            for(unsigned j=0;j<10u;j++){
                const unsigned ix=(next.head+j)%10u;
                const unsigned offset=(j&1u)?64u:0u;
                sum+=(double)qmf_coeff[j*64u+n]*
                     (double)next.history[ix][offset+n];
            }
            if(!isfinite(sum) || fabs(sum)>FLT_MAX)return 0;
            stage[(size_t)t*64u+n]=(float)sum;
        }
    }
    memcpy(output,stage,(size_t)slots*64u*sizeof(float));
    *state=next;
    return 1;
}
