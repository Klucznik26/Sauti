#ifndef SAUTI_AAC_SSR_H
#define SAUTI_AAC_SSR_H
/* AAC SSR (Scalable Sampling Rate, ISO/IEC 14496-3 object type 3): the gain control tool and its filter bank.
 *
 * Decoder side of one channel: the 1024 spectral lines are four bands of 256 (short windows: eight windows of 128, each four bands of 32); odd bands are in reverse order.  Every band has its own
 * IMDCT (256 / 32 lines, sine or KBD window), a time domain gain control function made from the gain_control_data() of the frame (it undoes the attenuation of attacks that the encoder applied to
 * suppress pre-echo), overlap-add, and the four band signals are joined by the inverse polyphase quadrature filter bank (96 taps).  Band 0 never carries gain control.
 *
 * The code is written for Sauti after reading the description of the tool in the ISO/IEC 14496-5 reference software (see third_party/iso14496-5/NOTICE); only the 48 coefficients of the PQF prototype
 * (sauti_aac_ssr_tables.c, generated by tools/gen_aac_ssr_tables.py) and the SSR TNS limits are data taken from it.  All arithmetic is in double. */
#include <stddef.h>
#include <stdint.h>

#define SAUTI_AAC_SSR_BANDS 4u
#define SAUTI_AAC_SSR_BAND_LINES 256u

typedef struct { uint8_t num; uint8_t lev[7]; uint8_t loc[7]; } SautiAacSsrGainInf;     /* gain changes of one band and one block: level code (4 bits) and location (2 / 4 / 5 bits) */
typedef struct {
    uint8_t max_band;                                                                   /* the 2-bit field: bands 1 .. max_band carry data */
    SautiAacSsrGainInf band[SAUTI_AAC_SSR_BANDS][8];                                    /* [band][block]: 1 block for long windows, 2 for start / stop, 8 for short windows */
} SautiAacSsrGain;
typedef struct {
    double overlap[SAUTI_AAC_SSR_BANDS][512];                                           /* per band, the second half of the previous frame (short windows use up to 400 entries) */
    SautiAacSsrGainInf prev[SAUTI_AAC_SSR_BANDS];                                       /* gain data of the last block of the previous frame, per band */
    double pqf0[2][24], pqf1[2][24];                                                    /* IPQF delay lines */
} SautiAacSsrState;

extern const double sauti_aac_ssr_pqf_half[48];                                         /* generated: tools/gen_aac_ssr_tables.py */
extern const uint8_t sauti_aac_ssr_tns_max_bands[12][2];                                /* per sampling_frequency_index: long, short window */

void sauti_aac_ssr_state_init(SautiAacSsrState *state);
/* gain_control_data() (after the gain_control_data_present flag) for the window sequence of the frame (0 long, 1 start, 2 eight short, 3 stop): 1 ok, 0 truncated or malformed. */
int sauti_aac_ssr_gain_parse(const uint8_t *data, size_t length, size_t *pos, unsigned window_sequence, SautiAacSsrGain *gain);
/* One frame of one channel: spectral[1024] -> out[1024] (time samples in the scale of the AAC-LC synthesis of Sauti).  gain == NULL means gain_control_data_present = 0 (no gain changes).
 * `previous_shape` / `shape`: window shapes (0 sine, 1 KBD) of the previous and the current frame.  1 ok, 0 invalid arguments. */
int sauti_aac_ssr_synthesis(SautiAacSsrState *state, unsigned window_sequence, unsigned previous_shape, unsigned shape,
                            const float spectral[1024], const SautiAacSsrGain *gain, float out[1024]);
#endif
